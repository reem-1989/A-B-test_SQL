"""
Generates the synthetic data for the Landing Page A/B Test project.

The experiment
--------------
FreshBox, a fictional meal-kit company, tested a new sign-up page
for two weeks (3-16 March 2025):

    Group A (control)   -> the current page: "Start your free trial"
    Group B (treatment) -> a new page: "Get 3 free meals this week"

Every new visitor was randomly assigned to A or B (50/50).
We recorded whether they signed up for the free trial.

Run:  python scripts/generate_data.py
Output: data/02_insert_data.sql  (INSERT statements for MySQL)
        data/ab_test_visitors.csv (same data as a CSV file)

The random seed is fixed, so the output is identical every time.
"""

import csv
import os
import random
from datetime import date, timedelta

random.seed(500)

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA_DIR = os.path.join(ROOT, "data")

START = date(2025, 3, 3)
DAYS = 14
VISITORS = 10_000

# "True" sign-up rates used to simulate each group.
# In a real test these are unknown: the analysis tries to estimate them.
SIGNUP_RATE = {"A": 0.100, "B": 0.118}

DEVICES = [("Mobile", 0.62), ("Desktop", 0.38)]
DEVICE_EFFECT = {"Mobile": 0.9, "Desktop": 1.2}   # desktop visitors sign up a bit more often


def pick(options):
    r, total = random.random(), 0
    for value, weight in options:
        total += weight
        if r < total:
            return value
    return options[-1][0]


def main():
    rows = []
    for visitor_id in range(1, VISITORS + 1):
        group = "A" if random.random() < 0.5 else "B"        # random assignment
        device = pick(DEVICES)
        visit_date = START + timedelta(days=random.randrange(DAYS))
        rate = SIGNUP_RATE[group] * DEVICE_EFFECT[device]
        signed_up = int(random.random() < rate)
        rows.append((visitor_id, group, device, visit_date.isoformat(), signed_up))

    cols = ["visitor_id", "test_group", "device", "visit_date", "signed_up"]

    with open(os.path.join(DATA_DIR, "ab_test_visitors.csv"), "w",
              newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(cols)
        w.writerows(rows)

    with open(os.path.join(DATA_DIR, "02_insert_data.sql"), "w", encoding="utf-8") as f:
        f.write("-- Data for the Landing Page A/B Test project (generated by scripts/generate_data.py)\n")
        f.write("-- Run 01_create_table.sql first.\n\n")
        f.write("USE ab_test;\n\n")
        for i in range(0, len(rows), 1000):
            batch = rows[i:i + 1000]
            f.write(f"INSERT INTO ab_test_visitors ({', '.join(cols)}) VALUES\n")
            f.write(",\n".join(f"({r[0]}, '{r[1]}', '{r[2]}', '{r[3]}', {r[4]})" for r in batch))
            f.write(";\n\n")

    print(f"ab_test_visitors  {len(rows):,} rows")


if __name__ == "__main__":
    main()
